import { useState, useEffect } from 'react';
import { supabase } from '@/integrations/supabase/client';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table';
import {
  Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle,
} from '@/components/ui/dialog';
import {
  AlertDialog, AlertDialogAction, AlertDialogCancel, AlertDialogContent,
  AlertDialogDescription, AlertDialogFooter, AlertDialogHeader, AlertDialogTitle,
} from '@/components/ui/alert-dialog';
import { Video, Loader2, Plus, Pencil, Trash2, Eye, EyeOff, Terminal } from 'lucide-react';
import { useToast } from '@/hooks/use-toast';

interface ZoomAccount {
  id: string;
  name: string;
  sdk_key: string;
  sdk_secret: string;
  meeting_id: string;
  passcode: string;
  is_active: boolean;
  created_at: string;
}

const emptyForm = {
  name: '',
  sdk_key: '',
  sdk_secret: '',
  meeting_id: '',
  passcode: '',
  is_active: true,
};

export default function AdminZoom() {
  const [accounts, setAccounts] = useState<ZoomAccount[]>([]);
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [dialogOpen, setDialogOpen] = useState(false);
  const [editingId, setEditingId] = useState<string | null>(null);
  const [form, setForm] = useState({ ...emptyForm });
  const [showSecret, setShowSecret] = useState(false);
  const [deleteId, setDeleteId] = useState<string | null>(null);
  const { toast } = useToast();

  useEffect(() => {
    fetchAccounts();
  }, []);

  const fetchAccounts = async () => {
    setLoading(true);
    const { data, error } = await supabase
      .from('zoom_accounts')
      .select('*')
      .order('created_at', { ascending: false });

    if (error) {
      toast({ title: 'Error loading Zoom setups', description: error.message, variant: 'destructive' });
    } else {
      setAccounts((data as ZoomAccount[]) || []);
    }
    setLoading(false);
  };

  const openCreate = () => {
    setEditingId(null);
    setForm({ ...emptyForm });
    setShowSecret(false);
    setDialogOpen(true);
  };

  const openEdit = (account: ZoomAccount) => {
    setEditingId(account.id);
    setForm({
      name: account.name,
      sdk_key: account.sdk_key,
      sdk_secret: account.sdk_secret,
      meeting_id: account.meeting_id,
      passcode: account.passcode,
      is_active: account.is_active,
    });
    setShowSecret(false);
    setDialogOpen(true);
  };

  const handleSave = async () => {
    if (!form.name.trim()) {
      toast({ title: 'Name is required', variant: 'destructive' });
      return;
    }
    setSaving(true);

    const payload = {
      name: form.name.trim(),
      sdk_key: form.sdk_key.trim(),
      sdk_secret: form.sdk_secret.trim(),
      meeting_id: form.meeting_id.replace(/\s/g, ''),
      passcode: form.passcode.trim(),
      is_active: form.is_active,
    };

    const { error } = editingId
      ? await supabase.from('zoom_accounts').update(payload).eq('id', editingId)
      : await supabase.from('zoom_accounts').insert(payload);

    setSaving(false);

    if (error) {
      toast({ title: 'Error saving', description: error.message, variant: 'destructive' });
      return;
    }

    toast({ title: editingId ? 'Zoom setup updated' : 'Zoom setup added' });
    setDialogOpen(false);
    fetchAccounts();
  };

  const handleDelete = async () => {
    if (!deleteId) return;
    const { error } = await supabase.from('zoom_accounts').delete().eq('id', deleteId);
    setDeleteId(null);
    if (error) {
      toast({ title: 'Error deleting', description: error.message, variant: 'destructive' });
      return;
    }
    toast({ title: 'Zoom setup deleted' });
    fetchAccounts();
  };

  const toggleActive = async (account: ZoomAccount) => {
    const { error } = await supabase
      .from('zoom_accounts')
      .update({ is_active: !account.is_active })
      .eq('id', account.id);
    if (error) {
      toast({ title: 'Error updating', description: error.message, variant: 'destructive' });
      return;
    }
    fetchAccounts();
  };

  return (
    <div className="space-y-6">
      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <Terminal className="w-5 h-5" />
            Edge Function
          </CardTitle>
          <CardDescription>
            Meeting signatures are generated by the backend function below using the active Zoom setup.
          </CardDescription>
        </CardHeader>
        <CardContent>
          <div className="flex items-center justify-between p-3 rounded-lg bg-muted/50 text-sm">
            <span className="text-muted-foreground">Function name</span>
            <code className="font-mono font-medium">zoom-signature</code>
          </div>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div>
              <CardTitle className="flex items-center gap-2">
                <Video className="w-5 h-5" />
                Zoom Setup ({accounts.length})
              </CardTitle>
              <CardDescription className="mt-1">
                Add, edit, or remove Zoom app credentials and meeting details.
              </CardDescription>
            </div>
            <Button onClick={openCreate}>
              <Plus className="w-4 h-4 mr-2" />
              Add Zoom Setup
            </Button>
          </div>
        </CardHeader>
        <CardContent>
          {loading ? (
            <div className="flex items-center justify-center h-40">
              <Loader2 className="w-8 h-8 animate-spin text-primary" />
            </div>
          ) : (
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Name</TableHead>
                  <TableHead>Meeting ID</TableHead>
                  <TableHead>Passcode</TableHead>
                  <TableHead>Status</TableHead>
                  <TableHead className="text-right">Actions</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {accounts.map((account) => (
                  <TableRow key={account.id}>
                    <TableCell className="font-medium">{account.name}</TableCell>
                    <TableCell>{account.meeting_id || '—'}</TableCell>
                    <TableCell>{account.passcode ? '••••' : '—'}</TableCell>
                    <TableCell>
                      <button onClick={() => toggleActive(account)}>
                        <Badge variant={account.is_active ? 'default' : 'secondary'}>
                          {account.is_active ? 'Active' : 'Inactive'}
                        </Badge>
                      </button>
                    </TableCell>
                    <TableCell className="text-right space-x-1">
                      <Button variant="ghost" size="icon" onClick={() => openEdit(account)}>
                        <Pencil className="w-4 h-4" />
                      </Button>
                      <Button variant="ghost" size="icon" onClick={() => setDeleteId(account.id)}>
                        <Trash2 className="w-4 h-4 text-destructive" />
                      </Button>
                    </TableCell>
                  </TableRow>
                ))}
                {accounts.length === 0 && (
                  <TableRow>
                    <TableCell colSpan={5} className="text-center text-muted-foreground py-8">
                      No Zoom setups yet
                    </TableCell>
                  </TableRow>
                )}
              </TableBody>
            </Table>
          )}
        </CardContent>
      </Card>

      <Dialog open={dialogOpen} onOpenChange={setDialogOpen}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>{editingId ? 'Edit Zoom Setup' : 'Add Zoom Setup'}</DialogTitle>
            <DialogDescription>
              Meeting details used by the reading room.
            </DialogDescription>
          </DialogHeader>
          <div className="space-y-4">
            <div className="space-y-2">
              <Label htmlFor="zoom-name">Name</Label>
              <Input
                id="zoom-name"
                value={form.name}
                onChange={(e) => setForm({ ...form, name: e.target.value })}
                placeholder="Reading Room Main"
              />
            </div>
            <div className="grid gap-4 sm:grid-cols-2">
              <div className="space-y-2">
                <Label htmlFor="zoom-meeting">Meeting ID</Label>
                <Input
                  id="zoom-meeting"
                  value={form.meeting_id}
                  onChange={(e) => setForm({ ...form, meeting_id: e.target.value })}
                  placeholder="123 456 7890"
                />
              </div>
              <div className="space-y-2">
                <Label htmlFor="zoom-pass">Meeting Passcode</Label>
                <Input
                  id="zoom-pass"
                  value={form.passcode}
                  onChange={(e) => setForm({ ...form, passcode: e.target.value })}
                  placeholder="Passcode"
                />
              </div>
            </div>
          </div>
          <DialogFooter>
            <Button variant="ghost" onClick={() => setDialogOpen(false)} disabled={saving}>
              Cancel
            </Button>
            <Button onClick={handleSave} disabled={saving}>
              {saving && <Loader2 className="w-4 h-4 animate-spin mr-2" />}
              {editingId ? 'Save Changes' : 'Add Setup'}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      <AlertDialog open={!!deleteId} onOpenChange={(open) => !open && setDeleteId(null)}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Delete this Zoom setup?</AlertDialogTitle>
            <AlertDialogDescription>
              This permanently removes the credentials and meeting details.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel>Cancel</AlertDialogCancel>
            <AlertDialogAction onClick={handleDelete}>Delete</AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
  );
}
